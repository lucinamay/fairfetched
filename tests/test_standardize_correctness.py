"""Chemistry correctness tests for `fairfetched.standardize`.

`test_standardize.py` covers plumbing: does an expression build, is the dtype
right, is the column non-null. Those tests all pass if `standardize()` quietly
becomes a no-op, so this file covers the other half -- whether the numbers
coming out are the right numbers, and whether the ways this module can fail are
visible to whoever is running it.

Expected values are taken from `tests/reference/standardize_reference.csv`, generated by
`tests/reference/generate.py`: So these tests compare fairfetched
against the underlying libraries (+ a published PubChem InChIKey where one exists).

Note: regenerate the file after upgrading RDKit or structure_pipelines

Dev note: current known 'bugs'/unimplementations are marked `xfail(strict=True)`.
Once fixed, these will 'fail' as unexpected passes: at that point, remove marker
"""

